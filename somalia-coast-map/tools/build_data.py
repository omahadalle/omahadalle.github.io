"""
Rebuild the map's data files from the spreadsheet CSV.

    pip install pandas
    python tools/build_data.py                       # uses data/somalia_coastal.csv
    python tools/build_data.py path/to/export.csv    # or a CSV downloaded from the Sheet

Writes:
    data/locations.js   the coastal places (window.COAST_LOCATIONS)
    data/land.js        Somalia's 18 regions (window.COAST_REGIONS), detailed neighbouring
                        countries (window.COAST_LAND), from the tools/ folder
    data/world.js       the rest of the world's countries (window.COAST_WORLD)

The data is written as .js files (not .json) so the map also works when
index.html is opened directly from your computer, not only from a web server.
"""
import json
import os
import sys
import re
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "somalia_coastal.csv")
WORLD = os.path.join(ROOT, "tools", "world.geojson")                # Natural Earth 1:50m, rest of the world
NEIGHBOURS = os.path.join(ROOT, "tools", "neighbours.geojson")      # Natural Earth 1:10m, countries near Somalia
REGIONS = os.path.join(ROOT, "tools", "somalia_regions.geojson")    # amCharts geodata (credit link required)

# Feature types -> map layer (index into GROUPS in js/map.js)
GROUP_TYPES = [
    ["Populated place", "Dispersed populated place", "Port", "Mosque", "Cemetery", "Ruin",
     "Tomb", "Lighthouse"],                                                     # 0 Settlements
    ["Well", "Wells", "Waterhole", "Spring", "Wadi", "Stream", "Intermittent stream", "Pond",
     "Lagoon", "Swamp", "Marsh"],                                               # 1 Water
    ["Cape", "Point", "Headland", "Peninsula", "Bay", "Cove", "Inlet", "Anchorage", "Beach",
     "Spit", "Peninsula-island"],                                               # 2 Capes, points & bays
    ["Island", "Islands", "Reef", "Shoal", "Bank", "Rock awash", "Rocks", "Bar"],  # 3 Islands, reefs
    ["Hill", "Hills", "Mountain", "Mountains", "Dune(s)", "Sand area", "Ridge", "Plain",
     "Pass", "Cave"],                                                           # 4 Hills, dunes & land
]
OTHER = len(GROUP_TYPES)                                                        # 5 Other
TYPE_TO_GROUP = {t: i for i, types in enumerate(GROUP_TYPES) for t in types}

df = pd.read_csv(CSV, dtype=str).fillna("")
df["lat"] = pd.to_numeric(df["Lat (decimal)"], errors="coerce")
df["lon"] = pd.to_numeric(df["Lon (decimal)"], errors="coerce")
df = df.dropna(subset=["lat", "lon"])

def tidy(name):
    """'Muqdisho [Somali], Mogadishu [conventional]' -> 'Muqdisho (Mogadishu)'."""
    if "[" not in name:
        return name
    m = re.match(r"^\s*(.+?)\s*\[\s*somali\s*\]\s*[,;]?\s*(.*?)\s*\[\s*conventional\s*\]\s*$", name, re.I)
    if m and m.group(2):
        return f"{m.group(1)} ({m.group(2)})"
    clean = re.sub(r"\s*\[\s*(somali|conventional)\s*\]\s*", " ", name, flags=re.I)
    return re.sub(r"\s+([,;])", r"\1", re.sub(r"\s+", " ", clean)).strip(" ,;")


points = [{
    "n": tidy(r["Name"]), "t": r["Feature type"], "r": r["Region"], "c": r["Coast"],
    "la": r["Latitude"], "lo": r["Longitude"], "y": round(r["lat"], 5), "x": round(r["lon"], 5),
    "a": r.get("Also known as (variant names)", ""), "p": r.get("Gazetteer page", ""),
    "u": r.get("Unverified †", "") == "Yes",
    "g": TYPE_TO_GROUP.get(r["Feature type"], OTHER),
} for _, r in df.iterrows()]

with open(os.path.join(ROOT, "data", "locations.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_data.py from the Gazetteer of Somalia (1987) coastal list.\n")
    f.write("window.COAST_LOCATIONS = " + json.dumps(points, ensure_ascii=False, separators=(",", ":")) + ";\n")

with open(os.path.join(ROOT, "data", "land.js"), "w", encoding="utf-8") as f:
    f.write("// Neighbouring countries: Natural Earth 1:10m (public domain), via the world-atlas package.\n")
    f.write("window.COAST_LAND = " + json.dumps(json.load(open(NEIGHBOURS, encoding="utf-8")), separators=(",", ":")) + ";\n")
    f.write("// Somalia regions: amCharts geodata (free linkware licence: keep the amCharts credit link on the map).\n")
    f.write("window.COAST_REGIONS = " + json.dumps(json.load(open(REGIONS, encoding="utf-8")), separators=(",", ":")) + ";\n")

with open(os.path.join(ROOT, "data", "world.js"), "w", encoding="utf-8") as f:
    f.write("// World countries: Natural Earth 1:50m (public domain), via the world-atlas package.\n")
    f.write("window.COAST_WORLD = " + json.dumps(json.load(open(WORLD, encoding="utf-8")), separators=(",", ":")) + ";\n")

print(f"Wrote data/locations.js ({len(points)} places), data/land.js and data/world.js")
